<h2>100ページのレポートを、3割の理解で受け取っていないか</h2>

<p>意外と誰も語らないけれど重要だと私が思っているのが、理解力です。</p>

<p>今はまだ、主従でいえば人間が主でAIが従。だとすれば人間は、AIがどういう考えを示し、どんな行動をするのかを十分に把握して理解する必要があります。</p>

<p>具体的な場面で言いましょう。ディープリサーチのような徹底的な調査レポート業務をAIに任せると、この先、100ページ分のレポートが平気で出てくるようになります。そのとき受け取る人間側の理解には、かなりのバラつきがあるはずなんです。3割ぐらいの理解で「分かった気」になって次のステップに進む人と、8割9割を確実に理解した上で次の行動を決める人。</p>

<p>この差で、意思決定も、進む方向も、全部変わってしまう。</p>

<p>いくらスペシャルなアドバイザー（AI）がついていても、受け取る人間が誤解したり、浅い理解のまま分かった気でいたら、そこから先の判断はズレていきます。言ってみれば、AIを部下に持つ「マネージャーとしての質」に差がつくということなんですよね。</p>

<h2>「理解格差」の3段階</h2>

<p>整理すると、AIの出力に対する人間側の姿勢は3段階に分かれると思っています。</p>

<p>1. 斜め読み——数十ページを流し読みして、3割の理解で「読んだこと」にする。<br>
2. 要約依存——AIに「もっと分かりやすく箇条書きで」と要約までさせて、ハイライトだけ理解する。<br>
3. 構造理解——結論だけでなく、その前提と根拠まで掴んで、次の問いを自分で立てられる。</p>

<p>白状すると、私自身もよくやるのは2番です。数十ページ規模のレポートが出てきたら、斜め読みした上で、さらにAIに要約させて、そこだけハイライト的に理解する。</p>

<p>これは全部読んで3割しか頭に残らないよりは十分にマシです。ただ、本来なら30ページ出てきたら30ページ丸々を100%理解できるのが理想で、それが人間にはなかなか難しい——だからこそ、ここが「人間対人間」で比較したときに差がつく能力になっていくと思うんですよね。</p>

