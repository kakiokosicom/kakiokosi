<p>議論への参加度が比較的低く、かつ議題の背景を理解しているメンバーが適任です。新人の練習台にされがちですが、専門用語や経緯を知らないと要点の取捨選択ができないため、重要な会議ほど経験者が担当するか、録音とセットで運用することをおすすめします。</p>

<h3>Q. 議事録はどのくらいの長さが適切ですか？</h3>
<p>社内定例なら議題1つにつき数行〜10行程度、A4で1〜2枚に収まるのが目安です。長さよりも「決定事項とアクションが明確か」が重要で、それが書けていれば短い議事録でも十分に機能します。</p>

<h3>Q. 発言者の名前は書くべきですか？</h3>
<p>決定事項・アクションアイテム・賛否が分かれた論点については発言者名を明記すべきです。一方、ブレストのような自由討議では、発言者名を出さずに意見だけを列挙したほうが率直な議論を妨げないという考え方もあり、会議の性質で使い分けます。</p>

<h3>Q. 録音だけしておけば議事録は不要ではないですか？</h3>
<p>録音は議事録の代わりにはなりません。1時間の会議の録音を聞き直すには1時間かかりますが、議事録なら数分で要点を把握できます。録音は「議事録の正確性を担保する原本」、議事録は「意思決定を共有する成果物」と役割が異なります。</p>

<h3>Q. AI議事録ツールがあれば人間の確認は不要になりますか？</h3>
<p>現状では不要にはなりません。AIは数字・固有名詞・否定表現を誤認識することがあり、また「どの発言が決定事項か」という文脈判断は会議の背景を知る人間にしかできません。AIで下書きを作り、人間が確定させるハイブリッド運用が現実解です。</p>

<h3>Q. 議事録の修正依頼が来たらどう対応すべきですか？</h3>
<p>共有時に訂正受付の期限を明示し、期限内の指摘は作成者が事実確認のうえ反映、期限後は次回会議の冒頭で承認を取って確定とするのが標準的な運用です。確定後の修正は履歴が残る形で行い、こっそり書き換えないことが信頼性の要です。</p>

