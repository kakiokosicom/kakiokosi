<p>再生環境と並んで効果が大きいのが、聴き始める前の下準備です。おすすめは、本格的な作業に入る前に音源全体を流し聞きするか、少なくとも冒頭と要所を拾い聞きしておくことです。話者の人数と声の特徴、話題の流れ、頻出する専門用語をあらかじめ把握しておくと、一文ごとの聴き取りで迷う時間が激減します。インタビューであれば質問項目のリスト、講演であれば配布資料に先に目を通しておくのも同じ効果があります。また、長時間音源は30分〜1時間程度のブロックに区切り、ブロックごとに「起こす→ざっと見直す」を繰り返すほうが、最後にまとめて見直すより集中力を保ちやすく、ミスの混入も防げます。</p>

<h2>表記統一ルールの作り方</h2>
<p>長い音源や複数人での分担作業では、表記ゆれが品質を大きく損ないます。作業を始める前に、最低限次の項目を決めた「表記ルール表」を作っておきましょう。</p>
<ol>
<li><strong>数字の表記：</strong>算用数字か漢数字か（例：「3つ」か「三つ」か）。桁区切りやパーセントの書き方もここで決めます。</li>
<li><strong>ひらく・とじるの基準：</strong>「事」と「こと」、「下さい」と「ください」、「致します」と「いたします」など、頻出語の漢字・かなを統一します。</li>
<li><strong>カタカナ語・英字：</strong>「サーバ」か「サーバー」か、「Web」か「ウェブ」か。納品先に既存の表記基準があれば必ず確認します。</li>
<li><strong>記号の使い方：</strong>聴取不能箇所は「（●●）」、笑いは「（笑）」、沈黙は「（沈黙）」など、注記記号を先に定義しておくと迷いがなくなります。</li>
<li><strong>話者表記：</strong>フルネームか、姓のみか、「A氏・B氏」か。敬称の有無も統一します。</li>
</ol>
<p>ルール表は一度作れば次の案件でも流用できます。作業中に迷った語はその都度ルール表に追記していくと、自分専用の用字用語集に育っていきます。</p>

<h2>ケバ取りの判断基準</h2>
<p>ケバ取りとは、意味を持たない言いよどみや口癖を取り除く処理です。難しいのは「どこまで取るか」の線引きで、次のような基準で考えると判断が安定します。</p>
<ul>
<li><strong>原則として取るもの：</strong>「あのー」「えっと」「まあ」「なんか」などの場つなぎ表現、「うんうん」「はいはい」といった聞き手の単純な相づち、同じ語の無意味な繰り返し（「それは、それはですね」→「それはですね」）。</li>
<li><strong>残すべきケース：</strong>同じ「あのー」でも、質問に対して長く考え込んでから発せられた「あのー……それは難しい質問ですね」のような言いよどみは、ためらいというニュアンス自体に意味があります。発言の心情が読み取れる言いよどみは残す、単なる口癖は取る、が基本線です。</li>
<li><strong>相づちの例外：</strong>「はい」が単なる相づちではなく質問への回答（同意）になっている場合は、削除すると意味が変わってしまいます。前後の文脈で機能を見極めましょう。</li>
</ul>
<p>迷ったら「削除しても発言の意味とニュアンスが変わらないか」を自問するのが、最もシンプルで確実な判断方法です。</p>

<h2>整文の度合いの決め方</h2>
<p>整文は話し言葉を書き言葉に整える処理ですが、強くかけるほど話者らしさは失われます。用途から逆算して度合いを決めましょう。</p>
<table>
<thead>
<tr><th>整文の度合い</th><th>処理の内容</th><th>向いている用途</th></tr>
</thead>
<tbody>
