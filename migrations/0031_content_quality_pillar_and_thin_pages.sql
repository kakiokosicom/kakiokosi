<li><strong>同音異義に注意：</strong>「カワサキ」が川崎か川﨑か河崎か、音だけでは判別できません。確認が取れない場合は無理に当て字をせず、カタカナ表記に注記を添えて納品時に申し送りします。</li>
</ol>

