<h2>自分で書き起こしをする手順</h2>
<p>書き起こしは特別な資格がなくても始められますが、段取りの良し悪しで作業時間と品質が大きく変わります。当編集部の実務経験をふまえ、4つのステップに分けて解説します。</p>

<h3>ステップ1：録音の準備（書き起こしは録音前から始まっている）</h3>
<p>書き起こしの品質を最も大きく左右するのは、実は<strong>元の音源の品質</strong>です。聞き取れない音声は、どれだけ時間をかけても正確には起こせません。録音の段階で次の点に注意しておくと、後工程が格段に楽になります。</p>
<ul>
<li>録音機器（ICレコーダーやスマートフォン）は話者のできるだけ近くに置く</li>
<li>空調や道路騒音などのノイズ源から離れた場所を選ぶ</li>
<li>複数人の会話では、冒頭に参加者が名乗ると話者特定がしやすくなる</li>
<li>可能であれば予備の録音機器を用意し、二重に録音する</li>
<li>登壇資料や参加者名簿など、固有名詞の確認に使える資料を入手しておく</li>
</ul>
<p>依頼する場合も自分で起こす場合も、この準備段階の重要性は変わりません。詳しくは<a href="/share/point">ご依頼準備のポイント</a>にまとめています。</p>

<h3>ステップ2：再生環境を整える</h3>
<p>作業効率は再生環境でほぼ決まります。最低限、次の3点を整えることをおすすめします。</p>
<ol>
<li><strong>再生速度の調整機能</strong> ― 聞き取りにくい箇所は0.5〜0.75倍速に落とし、聞き取りやすい箇所は等倍〜やや速めで進めると効率的です。</li>
<li><strong>数秒単位の巻き戻し操作</strong> ― 書き起こし作業では数秒の巻き戻しを何百回と繰り返します。キーボードショートカットやフットペダルで手を止めずに操作できると、作業時間を大幅に短縮できます。</li>
<li><strong>ヘッドホン・イヤホン</strong> ― スピーカー再生よりも細部の聞き取りがしやすく、ノイズの中の発言も拾いやすくなります。</li>
