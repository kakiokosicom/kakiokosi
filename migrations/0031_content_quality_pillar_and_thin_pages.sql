<p>注意したいのは、整文はあくまで「表現を整える」処理であって、発言内容の追加や削除は越権だということです。話者が言っていないことを書き足してしまえば、それはもう書き起こしではありません。</p>

<h2>固有名詞の確認方法</h2>
<p>人名・社名・地名・専門用語の誤りは、書き起こしの信頼性を最も損なうミスです。次の手順で確認しましょう。</p>
<ol>
<li><strong>資料を先に読む：</strong>講演資料・議事次第・参加者名簿など、音源に関連する資料があれば作業前に目を通します。登場しそうな固有名詞を先に把握しておくだけで、聴き取りの精度が変わります。</li>
