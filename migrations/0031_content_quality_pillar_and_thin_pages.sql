<h2>書き起こし（文字起こし）とは</h2>
<p>書き起こし（文字起こし）とは、講演・インタビュー・会議・スピーチなどの音声や映像コンテンツを、正確にテキスト（文字）に変換する作業のことです。「テープ起こし」「トランスクリプション」とも呼ばれます。</p>
<p>音声や映像は「聞く・観る」ためのメディアであり、検索したり、引用したり、流し読みしたりすることには向いていません。書き起こしは、話された言葉をテキストという扱いやすい形式に変換することで、情報の検索性・引用性・保存性を大きく高める作業です。議事録の作成、報道での発言引用、研究データの分析、字幕制作など、さまざまな場面で必要とされています。</p>
<p>書き起こし.comは2011年の運営開始以来、15年以上にわたって講演・スピーチ・インタビューの書き起こしに特化したメディアを運営してきました。本ページでは、その実務経験をもとに、書き起こしの基礎知識から具体的なやり方、AIツールとの付き合い方までを体系的に解説します。</p>

<h2>「書き起こし」「文字起こし」「テープ起こし」の違い</h2>
<p>書き起こしには複数の呼び方があり、初めて調べる方は戸惑うかもしれません。結論からいえば、<strong>どの呼び方も指している作業はほぼ同じ</strong>で、使われる場面や時代背景が異なるだけです。</p>
<ul>
<li><strong>書き起こし</strong> ― 音声・映像を文字にする作業全般を指す、もっとも広い言葉です。メディアや出版の現場でよく使われます。</li>
<li><strong>文字起こし</strong> ― 「書き起こし」とほぼ同義です。近年はAI音声認識ツールの普及にともない、「文字起こし」という呼び方が一般化しつつあります。</li>
<li><strong>テープ起こし</strong> ― カセットテープに録音した音声を文字に起こしていた時代の名残のある呼び方です。録音媒体がデジタルに移行した現在も、業界用語として広く通用しています。詳しくは<a href="/share/tapeokoshi">テープ起こしの基本情報</a>をご覧ください。</li>
<li><strong>トランスクリプション（transcription）</strong> ― 英語圏での呼称です。書き起こされたテキストそのものは「トランスクリプト（transcript）」と呼ばれます。海外の研究論文や字幕制作の文脈で登場します。</li>
</ul>
<p>このほか、議事録作成や反訳（裁判関係の用語）など、用途に特化した呼び方もあります。発注や情報収集の際は、呼び方の違いにこだわるよりも、「どの仕上げ方式を求めているか」を明確にするほうが重要です。次の章で詳しく説明します。</p>

<h2>書き起こしの3つの仕上げ方式</h2>
<p>書き起こしには、仕上がりの形式によって主に3つの方式があります。同じ音源でも、どの方式を選ぶかによって作業時間も成果物の性質も大きく変わるため、目的に応じた選択が欠かせません。</p>

<h3>1. 素起こし（逐語起こし）</h3>
<p>話者の発言を一言一句そのまま文字に起こす方式です。「えーと」「あのー」などのフィラー（つなぎ言葉）、言い間違い、言い直し、笑い声などもすべて忠実に記録します。</p>
<p>発言の正確な記録そのものに価値がある場合に選ばれる方式で、裁判記録、言語学などの学術研究、カウンセリングや質的調査の分析資料などで用いられます。話し方の癖や間合いまで含めて分析対象となる場面では、素起こし以外の方式は適しません。一方で、読み物としては冗長になるため、一般的なビジネス文書には向きません。</p>

<h3>2. ケバ取り</h3>
<p>フィラーや言い間違い、意味のない重複表現といった「ケバ」を取り除き、発言の内容を変えずに読みやすく整える方式です。話者の言葉づかいや語り口は残しつつ、不要な要素だけを除去します。</p>
<p>多くのビジネス用途や報道で標準的に使われる方式で、議事録、セミナー記録、インタビュー記事の素材などに適しています。書き起こし.comでも、この方式を基本として記事を制作しています。話者の個性を残しながら可読性を確保できる、バランスの取れた方式といえます。</p>

<h3>3. 整文（リライト）</h3>
<p>話し言葉を書き言葉に変換し、文法的に正しく、文章として完成された形に整える方式です。語順の入れ替え、冗長な表現の整理、「ら抜き言葉」の修正などを行います。</p>
<p>書籍化やウェブ記事化など、独立した読み物として公開することを前提とした場合に用いられます。ただし、整える度合いが大きくなるほど話者本来のニュアンスから離れるリスクもあるため、発言の趣旨を損なわない編集判断が求められます。</p>

