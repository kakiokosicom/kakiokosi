<h3>ステップ3：聴きながら入力する</h3>
<p>音声を聴きながらテキストを入力していきます。最初から完璧を目指さず、<strong>1周目は多少の聞き取り漏れを許容してざっくり起こし、2周目で穴を埋める</strong>という進め方が、結果的に速くなることが多いです。聞き取れない箇所は「●●（00:12:34）」のようにタイムスタンプ付きの印を残して先に進み、後でまとめて確認します。</p>
<p>複数人の会話では、話者の区別（「A：」「B：」など）を入力の段階から付けておきます。後から付け直すのは非常に手間がかかるためです。</p>

<h3>ステップ4：校正・仕上げ</h3>
<p>入力が終わったら、テキストを音声と照合しながら誤りを修正します。校正で特に注意すべきポイントは次のとおりです。</p>
<ul>
<li><strong>固有名詞・専門用語</strong> ― 人名、社名、製品名、業界用語は公式資料やウェブで表記を確認します。聞き取りだけに頼ると誤変換が残りやすい部分です。</li>
<li><strong>同音異義語</strong> ― 「保証/保障/補償」「異動/移動」など、文脈で判断が必要な語は重点的に確認します。</li>
<li><strong>数字・日付</strong> ― 金額や日付の誤りは実害につながりやすいため、必ず音声と再照合します。</li>
</ul>
<p>最後に、段落分け、話者表記の統一、見出しの付与などを行い、用途に応じた読みやすい形に整えれば完成です。</p>

<h2>所要時間の現実的な目安</h2>
<p>書き起こしを初めて行う方が最も驚くのが、作業にかかる時間です。一般的に、<strong>1時間の音源を書き起こすには4〜6時間程度かかる</strong>とされます。つまり音源の長さの4〜6倍です。タイピングに慣れていない方や、音質・話者数などの条件が悪い場合には、それ以上かかることも珍しくありません。</p>
<p>所要時間を左右する主な要因は次のとおりです。</p>
<ul>
<li><strong>音質</strong> ― ノイズが多い、音が小さい、反響があるなどの条件は、聞き直しの回数を大きく増やします。</li>
<li><strong>話者数</strong> ― 1人の講演よりも、複数人が発言を重ねる会議のほうが、話者特定と聞き分けに時間がかかります。</li>
<li><strong>話し方</strong> ― 早口、方言、専門用語の多さは作業時間を押し上げる要因です。</li>
<li><strong>仕上げ方式</strong> ― 素起こしは入力量が多く、整文は編集に時間がかかります。</li>
<li><strong>作業者の習熟度</strong> ― タイピング速度と書き起こしの経験値によって、同じ音源でも所要時間は大きく変わります。</li>
</ul>
<p>「会議の録音を自分で起こすつもりだったが、想像以上に時間がかかって本来の業務を圧迫してしまった」というのは非常によくある失敗です。作業時間を見積もったうえで、自分でやるか、AIツールを使うか、外部に依頼するかを判断することをおすすめします。</p>

