<h3>Apple純正メモ</h3>
<p>起動と記入は速いものの、フォルダ・ノートが増えると、あとで「あの一言」を探すコストが上がります。会議のためだけに専用ノートを作っても、結局そのノートを開きに行くワンステップが入るため、記録用のノートに混在しやすい。</p>

<h3>Notion / Obsidian</h3>
<p>知識管理には強いが、起動・同期・ページ遷移が「思いついた瞬間に書く」用途には重い。会議中に開いたページに勢いで書き足すと、議事録ノートと宿題メモが同居して、結局どこを見れば良いか分からなくなります。</p>

<h3>Gmailの下書き</h3>
<p>近いことができますが、毎回「新規メール → 宛先入力 → 件名入力」の手順がついて回り、メモ専用の動線にはなりません。下書きを送らないと受信箱に乗らない、という二段操作も会議中には地味に重い。</p>

<h3>Slackの自分DM</h3>
<p>起動の速さは高評価。ただし、検索精度・タグ付け・あとからの整理がメールより弱く、過去の宿題を1ヶ月後に掘り出すのが難しいケースがあります。チャットの流れに紛れて読み返さなくなる傾向もあります。</p>

