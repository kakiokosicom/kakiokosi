<h2>受信箱に一時メモを集約するメリット</h2>

<p>「あとで処理する一言」を自分のメール受信箱に投げる運用には、次のような利点があります。</p>

<ol>
<li><strong>処理する場所が一つに決まる</strong>。会議の宿題は受信箱、と決めておけば、議事録ノートを開かなくても抜け漏れチェックができます。</li>
<li><strong>メールの作法をそのまま使える</strong>。返信・転送・スター・スヌーズ・アーカイブが、受信箱に届いた瞬間から使えます。Slack DMにはない強みです。</li>
<li><strong>検索が強い</strong>。Gmailの検索演算子で、3ヶ月前の会議の宿題を一瞬で引き出せます。</li>
<li><strong>転送・共有が早い</strong>。受信したメモをそのまま同僚に転送するだけで、依頼や議事録の補足に変えられます。</li>
