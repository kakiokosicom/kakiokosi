<h2>よくある質問</h2>

<h3>受信箱に会議メモを送るとメールが溢れませんか？</h3>
<p>溢れます。だからこそ、受信箱を「処理待ちのToDo」として扱う前提が必要です。処理が終わったメモはアーカイブする、または専用ラベルに移すなどの運用ルールを最初に決めておきます。</p>

<h3>Slack DMではなぜダメなのですか？</h3>
<p>Slackは検索精度・通知ノイズ・履歴の流れやすさの観点で、長期処理に向きません。1日以内に消化する一時メモであればSlack DMでも問題ありませんが、1週間後に「あの宿題」を引き出す用途には弱いです。</p>

<h3>メールアドレスは仕事用と分けたほうが良いですか？</h3>
<p>分けても、分けなくても運用できます。仕事の宿題が多い人は、メモ専用のラベルやフィルタを作っておくと整理しやすくなります。</p>

<h3>会議の決定事項もメールで送ってよいですか？</h3>
<p>決定事項は議事録に書きます。受信箱に送るのは「自分が処理する一言」だけ、と分けるのが運用のコツです。</p>

<h3>Captioのようなアプリは他にありますか？</h3>
<p>iOSショートカットで自作する、Gmail下書きで運用する、Draftsで送信アクションを組む、シンプルメモのような専用アプリを使う、の4通りが現実的です。詳しい比較は<a href="/share/it/1380">Captio終了後、「自分にメールするメモ」をどう代替するか</a>を参照してください。</p>

