<li>送信</li>
</ol>

<h3>向き不向き</h3>
<ul>
<li><strong>向く</strong>：Markdownで書きたい人、複数の出力先（メール、Slack、Things）を切り替えたい人、すでにDraftsを使っている人</li>
<li><strong>向かない</strong>：Drafts自体を導入していない人。アプリ単体としては多機能で、メモ用途以外も含めて使いこなす前提のツールです</li>
