<h2>方法1：iPhone標準メールで自分宛てに送る</h2>

<p>最もシンプルな方法です。準備はほぼ不要で、メールアプリを開いて新規作成→宛先に自分のアドレスを入れて送信、です。</p>

<h3>具体的な手順</h3>
<ol>
<li>メールアプリを開く</li>
<li>右下の「新規作成」ボタンをタップ</li>
<li>宛先に自分のメールアドレスを入力（連絡先に自分を登録しておくと早い）</li>
<li>件名と本文を書いて送信</li>
</ol>

<h3>向き不向き</h3>
<ul>
<li><strong>向く</strong>：たまに自分にメールする人、追加アプリを増やしたくない人</li>
<li><strong>向かない</strong>：1日に何度も自分宛てメモを送りたい人。毎回の宛先入力・件名入力が手間になります</li>
</ul>

<p>連絡先に自分を登録しておけば、宛先の入力時間は数秒に短縮できます。それでも「件名を書く」というステップが残るため、頻繁に使う運用にはやや向きません。</p>

<h2>方法2：Gmail下書きを使う</h2>

<p>Gmail常用者には馴染みの方法です。Gmailアプリで自分宛てに新規メールを作り、送信します。</p>

<h3>具体的な手順</h3>
<ol>
<li>Gmailアプリを開く</li>
<li>右下のペンアイコンで新規メール作成</li>
<li>Toに自分のアドレス、件名と本文を入力して送信</li>
</ol>

<h3>こうすると少し早くなる</h3>
<ul>
<li>連絡先に自分のアドレスを登録しておく</li>
<li>署名にメモ用テンプレ（「メモ:」など）を仕込んで件名がなくても識別できるようにする</li>
<li>受信側でラベル「メモ」を自動付与するフィルタを作っておく</li>
</ul>

<p>方法1とほぼ同じ操作感ですが、Gmail側の検索とラベル機能が強力なので、後処理の効率は上がります。</p>

<h2>方法3：iOSショートカットを使う</h2>

<p>「自分にメール送信」をワンタップ実行するショートカットを作ると、起動から送信までが一段速くなります。Captio的な動作を、追加アプリなしで再現できる方法です。</p>

<h3>ショートカットの組み立て方</h3>
<ol>
<li>ショートカットアプリを開く</li>
<li>右上の「+」で新規作成</li>
<li>「入力を要求」アクションを追加（テキスト入力ダイアログを出す）</li>
<li>「メールを送信」アクションを追加し、宛先・件名を固定値で設定</li>
<li>本文に、3で取得した入力テキストを差し込む</li>
<li>ホーム画面に追加して、ワンタップで起動できるようにする</li>
</ol>

<h3>向き不向き</h3>
<ul>
<li><strong>向く</strong>：iOSショートカットの操作に慣れている人、宛先・件名を完全固定したい人、無料で済ませたい人</li>
<li><strong>向かない</strong>：ショートカット自体が初見の人。最初の組み立てに30分〜1時間ほどかかります</li>
</ul>

<p>一度作ってしまえば、起動 → 入力 → 送信が3秒以内に収まります。ショートカットの作り方を覚える時間を投資できる人には最適解の一つです。</p>

