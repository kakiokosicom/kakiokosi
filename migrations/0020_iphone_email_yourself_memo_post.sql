<h2>よくある質問</h2>

<h3>受信箱に自分宛てメールが溜まるのは問題ありませんか？</h3>
<p>運用次第です。自分のメモは「処理待ちのToDo」として扱い、処理が終わったらアーカイブする運用を最初に決めると整理しやすくなります。Gmailのフィルタで自分宛てメールに自動でラベル付与すると、通常の受信メールと分離できます。</p>

<h3>iOSショートカットでメール送信が動かないのですが</h3>
<p>iOS側の標準メール設定が必須です。設定アプリ →「メール」→「アカウント」で送信元アカウントが有効化されているか確認してください。Gmailアカウントのみで運用している場合、Gmailアプリではなく標準メールアプリの設定を使う仕様です。</p>

<h3>専用アプリと標準メールでは送信元アドレスが違いますか？</h3>
<p>どちらも、iPhoneに設定済みの送信用アカウントから送ります。受信側からは通常のメールとして届くため、見た目はほぼ同じです。設定で複数アカウントから選べる場合があります。</p>

<h3>Captio公式後継のアプリはありますか？</h3>
<p>公式後継アプリは確認できていません。Captioの操作感を別開発で再現したアプリとしてシンプルメモなどがあります。詳しくは<a href="/share/it/1380">Captio終了後、「自分にメールするメモ」をどう代替するか</a>を参照してください。</p>

<h3>Apple Watchから自分にメールできますか？</h3>
<p>標準メールアプリではApple Watchから新規メール作成と音声入力での送信が可能です。専用アプリの多くはWatch対応していないため、頻繁にWatchから送りたい場合は標準メールかiOSショートカットの方法が向きます。</p>

