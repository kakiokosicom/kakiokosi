-- 派生・断片の逐語書き起こし記事を noindex 化（品質集中戦略）
--
-- 背景:
--  GSC「クロール済み - インデックス未登録」が 30→62→71 と修正しても増え続けた。
--  excerpt 書き換え（0022/0023）を2回行っても再検証は2回とも失敗。原因はメタデータ
--  ではなく、対象が「TED Talks / 放送 / 国会質疑 / 企業プレゼンの逐語転載」かつ
--  「多パート分割の断片」で、一次ソースに対する独自付加価値が薄いこと（サイト全体の
--  品質・Helpful Content 判定）。メタ修正では永久にインデックスされない。
--
--  方針: これらを noindex=1 にして sitemap から除外し、クロール budget と内部リンク
--  評価を「インデックス可能な keeper 記事」へ集中させる。robots は `noindex, follow`
--  （article route 側で出力）なので keeper への内部リンク評価は温存される。
--  Google は noindex を「意図された除外」と認識し、GSC再検証で合格扱いになる。
--
--  非flagの単発書き起こし（Googleが既にインデックス済み）は対象外。あくまで
--  「弱い派生・断片」のみ。

ALTER TABLE posts ADD COLUMN noindex INTEGER NOT NULL DEFAULT 0;

