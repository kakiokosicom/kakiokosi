<h2>よくある質問</h2>

<h3>タイムスタンプメモはいつ書きますか？</h3>
<p>原則は録音中、その瞬間に書きます。会議が終わってから記憶で書くと、時刻が曖昧になり、後で該当箇所を探すコストが上がります。リアルタイムで書けない場合は、休憩のタイミングなどでまとめ書きすることもあります。</p>

<h3>1時間の会議で何個くらい書きますか？</h3>
<p>編集部の経験では、1時間あたり5〜15個が標準です。多すぎると後処理が重くなり、少なすぎると拾い漏れが増えます。「議事録のリードに使えるか」「あとで質問したいか」を判断基準に絞ると、自然にこの範囲に収まります。</p>

<h3>AI文字起こしを使えばタイムスタンプメモは不要ですか？</h3>
<p>不要にはなりません。AI文字起こしは「全文の保存」を担当し、タイムスタンプメモは「効く瞬間の選別」を担当します。役割が違うため、両方併用すると書き起こし後の編集が最も速くなります。</p>

<h3>音声録音アプリ内のブックマーク機能とは違いますか？</h3>
<p>違います。録音アプリ内のブックマークは、その録音ファイルの中でしか参照できません。タイムスタンプメモを別レイヤー（受信箱）に置くことで、複数の録音をまたいで横断検索でき、議事録ドラフト・取材原稿に転用しやすくなります。</p>

<h3>Captio代替で同じ運用ができるアプリはありますか？</h3>
<p>iOSショートカットを自作する、Gmailアプリで毎回送る、Draftsで送信アクションを組む、シンプルメモのような専用アプリを使う、の4通りが現実的です。詳しい比較は<a href="/share/it/1380">Captio終了後、「自分にメールするメモ」をどう代替するか</a>で扱っています。</p>

