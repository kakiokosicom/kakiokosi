<h2>タイムスタンプメモはどこに書くか</h2>

<p>場所選びが意外と重要です。録音アプリと別の場所に書く必要があります。理由は次の通り。</p>

<ul>
<li>録音アプリ内のメモ欄は、書き起こし後に取り出すのが面倒</li>
<li>議事録ノートに直接書くと、議事録ドラフトと混ざって整理しづらい</li>
<li>あとで「タイムスタンプメモだけ」をまとめて見たい</li>
</ul>

<p>このため、書き起こし.com編集部では「自分のメール受信箱」をタイムスタンプメモの保存先にしています。理由は次の通り。</p>

<ol>
<li>受信箱は録音アプリでも議事録ノートでもないため、レイヤーが分離する</li>
<li>あとから日付・キーワードで検索できる</li>
<li>必要な行だけ取材原稿の参考資料として転送できる</li>
<li>録音とテキストデータを別々に管理しているため、どちらかが消えても復旧できる</li>
</ol>

