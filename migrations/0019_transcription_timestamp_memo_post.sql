<h2>「短いラベル」の書き方</h2>

<p>ラベルが詳しすぎると会議に追いつけません。逆に短すぎると、あとで何を意味するか思い出せません。書き起こし.comでは、次のルールに落ち着きました。</p>

<ul>
<li><strong>固有名詞または数字を必ず1つ入れる</strong>。「Yamato Frame」「2026年Q3」「68%」など。</li>
<li><strong>感情を入れない</strong>。「すごい」「面白い」では検索できません。</li>
<li><strong>原文に近い動詞を入れる</strong>。「決まった」「却下」「保留」「再検討」など、決定状態が分かる動詞。</li>
</ul>

<p>例：×「ここ重要」 → ◯「12:40 A社見積、却下」</p>

