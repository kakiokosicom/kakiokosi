<h2>本題：丸投げが失敗し、二段ロケットが成功する構造</h2>

<p>さて、ここからが本題です。</p>

<p>多くの人がやりがちなのは、「作りたいもの」をいきなりManusに丸投げすることです。気持ちはわかります。最先端のエージェントなんだから、全部やってくれるはずだ、と。</p>

<p>でも、私はそうしません。</p>

<p>私のやり方は、ロケットの打ち上げに似ています。一段目で大気圏を抜け、切り離してから二段目で軌道に乗せる。<strong>一段目がClaude 3.7、二段目がManus</strong>。この順番と切り離しが、丸投げとの決定的な違いなんですよね。</p>

<h3>一段目：Claude 3.7に「仕様書」を書かせる</h3>

<p>最初にやるのは、Manusではなく、Claude 3.7 Sonnetに頼むことです。</p>

<p>頼み方にコツがあります。「あなたはその道20年30年の戦士で、プロフェッショナルですよね」と役を与える。そのうえで、「これから新人のエンジニアに渡すために、細かく定義されたプロダクトの仕様書・設計書・機能一覧をまとめてください」とお願いするんです。出発点は、たった2、3行の「こういう問題を解決するサービスを作りたい」だけでいい。</p>

<p>するとどうなるか。</p>

<p>ものの数分で、1万文字まではいかないにせよ、数千文字規模のざっくりした仕様書が出てきます。これを一つひとつ漏れなく読んでもいいんですが、長すぎるときは「要約して」とClaudeに頼む。さらに「これを要約して、ハイライトだけに絞り込んで」と重ねる。そうやって圧縮されたものをレビューするんですよね。</p>

<p>「内容的に合っているな」「この機能が足りないから足しておいて」。そうやってもう一度ブラッシュアップする。ここまでが一段目です。</p>

<h3>二段目：磨いた仕様書をManusに投げ込む</h3>

<p>仕様が固まって初めて、それをManusに投げ込みます。</p>

<p>Manusはエージェントとして、今おそらく最先端を進んでいます。投げ込むと、本当に10分、20分ぐらい帰ってこないことがあるぐらい、開発タスクを完全に自動で動かしてくれる。コーディングまでやって、Pythonファイルまで書いてくれるわけなんですよね。</p>

<p>私が今回やろうとしていたのは、一定間隔でプログラムが自動的に起動して、別のプログラムと連動しながら、とある作業を完了させる——そういう仕組みでした。</p>

<p>いきなり全部を作らせるのではなく、まずはミニマムな機能開発から始めるのがポイントです。本格的な定期業務に入る前に、「このプログラムが期待通りに動くか」という最小単位で試す。たとえば——これは今回実際に使ったわけではないんですが——「Xの自分の投稿のAPIを呼んで、最新100件を分析する」みたいな依頼があったとします。その場合、まずXのAPIとシステムが接続できるよう設計し、管理画面でAPIキーを取得し、今回はGitHub上で秘密鍵的なものを安全に管理する仕組みを用意したうえで、APIを叩いて100件を取得する。そこが動くかをテストしていくわけです。</p>

<h3>切り離しと再点火：エラーは「もう一段目」に戻す</h3>

<p>ここで、二段ロケットの真骨頂が出ます。</p>

<p>一発で正しいファイルが出てこないことは、当然あります。構文の間違いなどでエラーが出る。そのときはまず、「エラーが出てるけど直して」とManusに戻す。するとManusがもう一度確認し直して、「この点が間違っていました」と修正してくれる。</p>

<p>それでも解決しないときが、勝負どころなんですよね。</p>

<p>その場合、私はそのエラーをClaude 3.7の方に投げます。すると、Claudeが多角的な視点で修正案を出してくれる。それをまたManusに投げ込むと、さっと修正が完了して、無事にシステムが仕様通りに動き出す。</p>

<p>一段目（Claude）で設計し、二段目（Manus）で実装し、詰まったらもう一度一段目に戻して再点火する。この往復こそが、丸投げでは絶対に再現できない部分なんです。</p>

<h2>フレームワーク：個人がAI自動開発を回す4つの条件</h2>

<p>ここまでの実践を、私なりに構造化しておきます。</p>

<p>単なる手順の話ではなく、「これが揃っていれば個人でも自動開発が回る」という4つの条件として整理すると、こうなるんですよね。</p>

<ol>
<li><strong>条件1：丸投げしない（二段構成にする）</strong>——作りたいものを直接エージェントに渡さない。まずClaudeに仕様書を書かせ、磨いてからManusに渡す。設計と実装を分けることが、すべての土台です。</li>
<li><strong>条件2：最小単位から始める</strong>——いきなり完成品を狙わない。「この機能が単体で動くか」というミニマムなテストから積み上げる。動く部品を増やしていく感覚です。</li>
<li><strong>条件3：エラーを別のAIに往復させる</strong>——詰まったらManus内で粘りすぎない。Claudeに投げて視点を変え、その答えをManusに戻す。AIを1つに依存させず、相互補完で抜ける。</li>
<li><strong>条件4：人間の役割を「外部接続」と「最終判断」に絞る</strong>——APIキーの取得、GitHubでの鍵管理、セキュリティの最終チェック。今この瞬間に人間が担うべきは、コードを書くことではなく、外の世界とのつなぎ込みと、品質の見極めだけです。</li>
</ol>

<p>この4条件を押さえておくと、新しいAIサービスが出てきても「どこを任せて、どこを自分で握るか」の判断がぶれなくなります。道具は変わっても、この骨格は当分変わらないと私は見ています。</p>

<h2>「コードを読まない」リスクと、その潰し方</h2>

