<h2>【パジの独自フレーム】自動開発時代に、人間に残る4つの層</h2>

<p>ここからが本題です。「じゃあ人間は何をするの？」という問いに、ぼんやり答えても仕方ない。AIエージェントが開発の主役になった世界で、人間の役割がどこに退避していくのかを、パジは4つの層で整理しました。名付けて<strong>「方向・編集・責任・問い」の4層</strong>です。</p>

<h3>第1層：方向（ディレクション）— 何を作るかを指し示す</h3>
<p>AIエージェントは「作る」ことはできても、「何を作るべきか」を最初に決める起点にはなりにくい。チャットや画像、動画で「こっちに行ってくれ」と方向を与える役割は、当面いちばん人間に残ります。ディレクター職やプロデューサー職の本質が、ここに凝縮されていくとパジは見ています。実装力ではなく、行き先を指す力です。</p>

<h3>第2層：編集（ズレの修正）— 出てきたものを直す</h3>
