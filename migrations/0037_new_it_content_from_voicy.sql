<p>ただ、一定のセキュリティレベルでよければ、面白い手があります。</p>

<p>出来上がったファイルをダウンロードして、それをClaudeに投げ込むんです。「ここにセキュリティホールはあるか」「どういう点に注意すればいいか」と。すると、人間が今から学習して身につけるよりも、はるかに高い精度で——おそらく80点、90点ぐらいのレベルで——セキュリティホールを潰したコーディングにまで持っていける。守りの部分すら、AIに点検させられる時代になっているわけです。</p>

<p>そもそも、「GitHubやXのAPIの設計の仕方がわからない」という人もいると思います。私もそうでした。でも、それも問題になりません。</p>

<p>画面のキャプチャを撮って、「この機能やメニューはどこにあるの？」とClaudeに投げ込む。すると、ほとんどの確率で、すぐに正しい情報が返ってくる。その通りに実践していけば、完全にゼロからのスタートであっても、かなりのシステム開発ができてしまう。</p>

<p>必要なのは、技術力そのものよりも——<strong>やりたいことと、諦めない心</strong>。今の段階では、まだそれが効くフェーズなんですよね。</p>

