<li><strong>メモを整理しなくていい</strong>。フォルダ分けもタグ付けも不要で、書いたら送るだけ。</li>
<li><strong>自分の受信箱に届く</strong>。普段使っているメーラーが、そのまま「あとで処理する場所」になる。</li>
<li><strong>あとでメールとして処理できる</strong>。返信・転送・スター・アーカイブ・検索といった、メールの作法をそのまま使える。</li>
<li><strong>ToDo化・転送・検索が早い</strong>。Gmailラベルや検索演算子と相性が良い。</li>
<li><strong>高機能メモアプリより圧倒的に軽い</strong>。起動して即書ける。</li>
<li><strong>会議中・移動中に向いている</strong>。離席タイミングや電車内でも、思いついた瞬間に投げ込める。</li>
</ul>

<p>つまりCaptioの価値は「高機能であること」ではなく「自分にメールするだけ」という思い切った割り切りにあった、というのが私たちの理解です。</p>

<h2>Captio終了後に困るポイント</h2>

<p>同じ用途を別のツールで再現しようとすると、意外と詰まります。実際に書き起こし.comの編集メンバーで試してみたところ、それぞれ次のような壁がありました。</p>

<ul>
<li><strong>Apple純正メモ</strong>は、起動・記入は速いものの、保存先がフォルダごとに分散しがち。あとから処理する場所が一つにまとまらない。</li>
<li><strong>NotionやObsidian</strong>は知識管理には強いが、起動・同期・ページ遷移が「思いついた瞬間に書く」用途には重い。</li>
<li><strong>Gmailの下書き</strong>は近いことができるが、毎回「新規メール → 宛先入力 → 件名入力」の手順がついて回り、メモ専用の動線にはならない。</li>
<li><strong>iOSショートカット</strong>で擬似的に組めるものの、宛先・件名・署名・送信処理を自分で組み立てる必要があり、設定の手間がそれなりにかかる。</li>
<li><strong>音声入力やボイスメモだけで運用</strong>すると、後から処理する場所がカメラロールやファイルアプリに散らばり、文字起こし前の「目印」として使いにくい。</li>
</ul>

