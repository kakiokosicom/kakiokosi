// Generate SQL
const articles = JSON.parse(process.argv[2] || "[]");

const statements = [];
const now = "2026-03-28 00:00:00";

for (const art of articles) {
  const specific = ARTICLE_UPDATES[art.id];
  const generic = getGenericUpdate(art.title, art.cat, art.date);
  const update = specific || generic;

  const headerHtml = `<div class="editorial-note"><p><strong>【編集部注・2026年3月更新】</strong>${escSql(update.header)}</p></div>`;
  const footerHtml = `<div class="editorial-note editorial-note-footer"><p><strong>【2026年3月 編集部追記】</strong>${escSql(update.footer)}</p></div>`;

  // Use SQL string concatenation to prepend header and append footer
  // But first check if editorial note already exists
  statements.push(
    `UPDATE posts SET content = '${headerHtml}' || content || '${footerHtml}', updated_at = '${now}' WHERE id = ${art.id} AND content NOT LIKE '%editorial-note%';`
  );
}

function escSql(str) {
  return str.replace(/'/g, "''");
}

// Split into batches of 10 statements (D1 limit)
const BATCH_SIZE = 10;
for (let i = 0; i < statements.length; i += BATCH_SIZE) {
  const batch = statements.slice(i, i + BATCH_SIZE);
  const batchNum = Math.floor(i / BATCH_SIZE) + 1;
  const filename = `/tmp/kakiokosi_update_batch_${batchNum}.sql`;
  writeFileSync(filename, batch.join("\n"));
  console.log(`Wrote ${filename} (${batch.length} statements)`);
}

console.log(`\nTotal: ${statements.length} statements in ${Math.ceil(statements.length / BATCH_SIZE)} batches`);
console.log("\nTo execute, run:");
for (let i = 0; i < Math.ceil(statements.length / BATCH_SIZE); i++) {
  console.log(`npx wrangler d1 execute kakiokosi-db --remote --file=/tmp/kakiokosi_update_batch_${i + 1}.sql`);
}
